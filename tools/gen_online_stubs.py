"""Generate the libSceNpCppWebApi offline stubs from the import fixture.

Input : pkg/emitter/testdata/online_stub_imports.txt (library, NID, name) - Sony API identifiers only.
Output: pkg/runtime/modules/libSceNpCppWebApi/nps5_npcppwebapi_stubs.c   (one shim per import)
        pkg/emitter/online_stubs_cppwebapi_gen.go                       (binding tables)

The title bundles libSceNpCppWebApi.prx, which the loader skips on purpose (IsSystemStubModule), so its
exports the eboot imports have no code. Each gets a stub whose return value is chosen from the
demangled name (c++filt), because the C++ signatures are not recoverable from the mangling:
  constructor / destructor      return `this` (rdi); IntrusivePtr<T> constructors also zero the pointer
  getters, setters, operators,  return 0 (null / false / 0)
  size/begin/end, *IsSet, ...
  terminate                     return 0
  everything else (create, initialize, start, finish, Api calls, ...)  return SCE_NP_WEBAPI_ERROR_NOT_SIGNED_IN
Imports whose name is unknown (NID only) take the error return.
Run: python3 tools/gen_online_stubs.py
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIX = os.path.join(ROOT, "pkg/emitter/testdata/online_stub_imports.txt")
OUT_C = os.path.join(ROOT, "pkg/runtime/modules/libSceNpCppWebApi/nps5_npcppwebapi_stubs.c")
OUT_GO = os.path.join(ROOT, "pkg/emitter/online_stubs_cppwebapi_gen.go")

NEUTRAL = re.compile(r"^(get|set|is|has|size|begin|end|pushBack|clear|empty|reserve|resize|swap|reset|copyFrom|c_str)|IsSet$|^operator")


def components(nm):
    comps, cur, depth, i = [], "", 0, 0
    while i < len(nm):
        ch = nm[i]
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if depth == 0 and nm[i:i + 2] == "::":
            comps.append(cur); cur = ""; i += 2; continue
        cur += ch; i += 1
    comps.append(cur)
    return comps


def classify(demangled):
    depth, st = 0, None
    for i, ch in enumerate(demangled):
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        elif ch == "(" and depth == 0 and not demangled[:i].endswith("operator"):
            st = i; break
    nm = demangled if st is None else demangled[:st]
    comps = components(nm)
    base = re.sub(r"<.*", "", comps[-1]).strip()
    cls = re.sub(r"<.*", "", comps[-2]) if len(comps) > 1 else ""
    if base == cls:
        return "this_intrusive" if cls == "IntrusivePtr" else "this"
    if base.startswith("~"):
        return "this"
    if base == "terminate" or NEUTRAL.search(base):
        return "zero"
    return "error"


def main():
    rows = []
    for l in open(FIX):
        if l.startswith("#") or not l.strip():
            continue
        lib, nid, name = l.rstrip("\n").split("\t")
        if lib == "libSceNpCppWebApi":
            rows.append((nid, None if name == "-" else name))
    names = [n for _, n in rows if n]
    dem = subprocess.run(["c++filt"], input="\n".join(names), capture_output=True, text=True, check=True).stdout.split("\n")
    dmap = dict(zip(names, dem))

    def ident(nid, name):
        if name:
            return name
        return "npcppwebapi_nid_" + nid.replace("+", "_P_").replace("-", "_M_")

    rows.sort(key=lambda r: (r[1] is None, r[1] or r[0]))
    with open(OUT_C, "w") as c:
        c.write("// SPDX-License-Identifier: GPL-2.0-or-later\n// GENERATED by tools/gen_online_stubs.py from pkg/emitter/testdata/online_stub_imports.txt. Do not edit.\n"
                "// libSceNpCppWebApi offline stubs: the title bundles the PRX, the loader skips it, so its exports the eboot\n"
                "// imports are bound here. See docs/m2/online_stubs.md.\n#include \"nps5_online.h\"\n\n")
        c.write("#define CPP_ERR(fn, disp) void shim_##fn(GuestContext *ctx) { ON_RET(disp, ON_WEBAPI_ERROR_NOT_SIGNED_IN); }\n"
                "#define CPP_ZERO(fn, disp) void shim_##fn(GuestContext *ctx) { ON_RET64(disp, 0); }\n"
                "#define CPP_THIS(fn, disp) void shim_##fn(GuestContext *ctx) { ON_RET64(disp, ctx->rdi); }\n"
                "#define CPP_THIS_PTR(fn, disp) void shim_##fn(GuestContext *ctx) { on_put64(ctx, ctx->rdi, 0); ON_RET64(disp, ctx->rdi); }\n\n")
        kinds = {"error": "CPP_ERR", "zero": "CPP_ZERO", "this": "CPP_THIS", "this_intrusive": "CPP_THIS_PTR"}
        stats = {}
        for nid, name in rows:
            k = classify(dmap[name]) if name else "error"
            stats[k] = stats.get(k, 0) + 1
            disp = name if name else "NID " + nid
            c.write('%s(%s, "%s")\n' % (kinds[k], ident(nid, name), disp))
    with open(OUT_GO, "w") as g:
        g.write("// Code generated by tools/gen_online_stubs.py from testdata/online_stub_imports.txt; DO NOT EDIT.\n\npackage emitter\n\n")
        g.write("// cppWebApiShims: libSceNpCppWebApi imports with a known (mangled) name, bound by name and derived NID.\nvar cppWebApiShims = []string{\n")
        for nid, name in rows:
            if name:
                g.write('\t"%s",\n' % name)
        g.write("}\n\n// cppWebApiNIDShims: imports whose name is unknown, bound by NID only (NID -> shim).\nvar cppWebApiNIDShims = map[string]string{\n")
        for nid, name in rows:
            if not name:
                g.write('\t"%s": "shim_%s",\n' % (nid, ident(nid, None)))
        g.write("}\n")
    print(len(rows), "stubs", stats)


if __name__ == "__main__":
    main()
