var fallbackShimNames = func() map[string]bool {
	m := make(map[string]bool, len(libcShims))
	for _, n := range libcShims {
		m["shim_"+n] = true
	}
	return m
}()

// isFallbackShim reports whether shim is an HLE libc shim that yields to the guest's own
// definition of the function.
func isFallbackShim(shim string) bool { return fallbackShimNames[shim] }

func init() {
	for _, n := range libcShims {
		if _, dup := CanonicalShims[n]; !dup {
			CanonicalShims[n] = "shim_" + n
		}
	}
}
