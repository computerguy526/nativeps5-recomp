package diag

import (
	"fmt"
	"os"
	"path/filepath"
)

// ImportEntry is one row of imports.json.
type ImportEntry struct {
	Library string `json:"library"`
	NID     string `json:"nid"`
	Name    string `json:"name"`
	Status  string `json:"status"` // bound | stub | missing | excluded-module
	Via     string `json:"via,omitempty"`
	Relocs  int    `json:"relocs"`
}

// Imports is imports.json.
type Imports struct {
	NeededLibs []string      `json:"needed_libs"`
	Bound      int           `json:"bound"`
	Stub       int           `json:"stub"`
	Missing    int           `json:"missing"`
	Excluded   int           `json:"excluded,omitempty"`
	Imports    []ImportEntry `json:"imports"`
}

// BuildInfoC returns the C source of nps5_buildinfo.c, which stamps the translate bundle
// identity, the input hash and the addrmap location into the binary for the run bundle manifest.
func BuildInfoC(commit string, dirty bool, inputSHA, inputPath, addrmapPath, translateBundle string, imageSize int) string {
	q := func(s string) string { return fmt.Sprintf("%q", s) }
	d := 0
	if dirty {
		d = 1
	}
	return "// Generated by nps5 translate; read by nps5_diag.c.\n" +
		"const char nps5_build_commit[] = " + q(commit) + ";\n" +
		"const int nps5_build_dirty = " + fmt.Sprint(d) + ";\n" +
		"const char nps5_input_sha256[] = " + q(inputSHA) + ";\n" +
		"const char nps5_input_path[] = " + q(inputPath) + ";\n" +
		"const char nps5_addrmap_path[] = " + q(addrmapPath) + ";\n" +
		"const char nps5_translate_bundle[] = " + q(translateBundle) + ";\n" +
		"const unsigned long long nps5_guest_image_size = " + fmt.Sprint(imageSize) + "ULL;\n"
}

// WriteBuildInfo writes nps5_buildinfo.c into dir and returns its path.
func WriteBuildInfo(dir string, b *Bundle, inputSHA, inputPath, addrmapPath string, imageSize int) (string, error) {
	ti := toolInfo()
	p := filepath.Join(dir, "nps5_buildinfo.c")
	abs, _ := filepath.Abs(addrmapPath)
	bd, _ := filepath.Abs(b.Dir)
	return p, os.WriteFile(p, []byte(BuildInfoC(ti.GitCommit, ti.GitDirty, inputSHA, inputPath, abs, bd, imageSize)), 0o644)
}

// SummaryLine is a one-line census summary for logs.
func (c *Census) SummaryLine() string {
	return fmt.Sprintf("%d functions emitted (%d found, %d FDEs), %d unsupported stubs, %d/%d jump-table sites recovered, %d indirect calls",
		c.FunctionsEmitted, c.FunctionsFound, c.FDECount, c.UnsupportedTotal, c.JumpTablesRecover, c.IndirectJmpSites, c.IndirectCalls)
}
