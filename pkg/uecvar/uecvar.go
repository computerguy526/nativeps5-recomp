// Package uecvar finds Unreal Engine console-variable names in a game binary and turns a per-game
// profile (name=value lines) into a VFS overlay (Engine.ini [SystemSettings] + UECommandLine.txt)
// the runtime serves over /app0. See docs/m3/uecvar.md.
package uecvar

import (
	"bufio"
	"fmt"
	"io"
	"regexp"
	"sort"
	"strings"
)

// Prefixes of console variables the engine registers (a name must also be a dotted identifier).
var prefixes = []string{"r.", "t.", "p.", "fx.", "sg.", "a.", "au.", "con.", "net.", "vr.", "wp.", "s.", "gc.", "grass.", "foliage.", "niagara.", "ai.", "rhi.", "Slate."}

var nameRE = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z0-9_\[\]]+)+$`)

// Scan returns the sorted unique cvar-looking names found as UTF-16LE, UTF-32LE or ASCII
// strings in data. A name is a dotted identifier with a known prefix; false positives (file
// names, class paths) are possible, so the profile check below is what decides, not this list.
func Scan(data []byte) []string {
	set := map[string]bool{}
	add := func(s string) {
		if len(s) < 4 || len(s) > 160 || !nameRE.MatchString(s) {
			return
		}
		for _, p := range prefixes {
			if strings.HasPrefix(s, p) {
				set[s] = true
				return
			}
		}
	}
	for _, width := range []int{1, 2, 4} {
		var cur []byte
		for i := 0; i+width <= len(data); i += width {
			ok := true
			for k := 1; k < width; k++ {
				if data[i+k] != 0 {
					ok = false
				}
			}
			c := data[i]
			if ok && c >= 0x20 && c < 0x7f {
				cur = append(cur, c)
				continue
			}
			if len(cur) > 0 {
				add(string(cur))
				cur = cur[:0]
			}
		}
		add(string(cur))
	}
	// strings may start at an odd offset for the 2- and 4-byte widths; the aligned pass above is
	// enough in practice (UE's TEXT() literals are naturally aligned), so no second pass.
	out := make([]string, 0, len(set))
	for s := range set {
		out = append(out, s)
	}
	sort.Strings(out)
	return out
}

// Entry is one profile line.
type Entry struct {
	Section string // ini section, default SystemSettings
	Name    string
	Value   string
	Line    int
}

// Profile is a parsed .uecvars file.
type Profile struct {
	Entries []Entry
	Cmdline []string // @cmdline arguments appended to UECommandLine.txt
}

// Parse reads the profile format: "name=value" per line, "#" or ";" comments, "[Section]" to
// change the ini section (default SystemSettings), "@cmdline <args>" for command-line additions.
func Parse(r io.Reader) (*Profile, error) {
	p := &Profile{}
	sec := "SystemSettings"
	sc := bufio.NewScanner(r)
	for n := 1; sc.Scan(); n++ {
		l := strings.TrimSpace(sc.Text())
		if i := strings.Index(l, " #"); i >= 0 {
			l = strings.TrimSpace(l[:i])
		}
		switch {
		case l == "" || l[0] == '#' || l[0] == ';':
		case l[0] == '[' && l[len(l)-1] == ']':
			sec = l[1 : len(l)-1]
		case strings.HasPrefix(l, "@cmdline"):
			p.Cmdline = append(p.Cmdline, strings.TrimSpace(strings.TrimPrefix(l, "@cmdline")))
		default:
			k, v, ok := strings.Cut(l, "=")
			k, v = strings.TrimSpace(k), strings.TrimSpace(v)
			if !ok || k == "" || v == "" {
				return nil, fmt.Errorf("line %d: want name=value, got %q", n, l)
			}
			p.Entries = append(p.Entries, Entry{sec, k, v, n})
		}
	}
	return p, sc.Err()
}

// Unknown returns the SystemSettings-style entries whose name is not in names (a Scan result).
// Only meaningful for entries in [SystemSettings]/[ConsoleVariables]: other sections hold
// property names, not cvars.
func (p *Profile) Unknown(names []string) []Entry {
	have := map[string]bool{}
	for _, n := range names {
		have[strings.ToLower(n)] = true
	}
	var out []Entry
	for _, e := range p.Entries {
		if (e.Section == "SystemSettings" || e.Section == "ConsoleVariables") && !have[strings.ToLower(e.Name)] {
			out = append(out, e)
		}
	}
	return out
}

// EngineINI renders the profile as the Engine.ini the engine reads last (Saved/Config/<platform>/Engine.ini).
func (p *Profile) EngineINI() string {
	var b strings.Builder
	b.WriteString("; generated by cmd/uecvar from a profile: do not edit\n")
	var order []string
	by := map[string][]Entry{}
	for _, e := range p.Entries {
		if _, ok := by[e.Section]; !ok {
			order = append(order, e.Section)
		}
		by[e.Section] = append(by[e.Section], e)
	}
	for _, s := range order {
		fmt.Fprintf(&b, "\n[%s]\n", s)
		for _, e := range by[s] {
			fmt.Fprintf(&b, "%s=%s\n", e.Name, e.Value)
		}
	}
	return b.String()
}

// CommandLine merges the original UECommandLine.txt content with the profile's @cmdline additions.
func (p *Profile) CommandLine(orig string) string {
	parts := []string{strings.TrimSpace(orig)}
	parts = append(parts, p.Cmdline...)
	var out []string
	for _, s := range parts {
		if s != "" {
			out = append(out, s)
		}
	}
	return strings.Join(out, " ") + "\n"
}
